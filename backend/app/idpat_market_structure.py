"""IDPAT-3 causal liquidity and market-structure research adapter.

Reuses existing NEPSE scanner structure/Wyckoff engines. It does not create a
second BOS/CHoCH engine, infer hidden orders, or emit trade instructions.
"""
from __future__ import annotations

from datetime import date
from decimal import Decimal

from app.idpat_price_volume import (
    IDPATError,
    _decimal,
    _timestamp,
    analyze_idpat_price_volume,
)
from app.market_structure import detect_structure
from app.smc_multitimeframe import evaluate_multitimeframe
from app.wyckoff_features import wyckoff_event_features


def _withheld(symbol, reason, coverage=None):
    return {
        "symbol": symbol,
        "schema_version": "idpat-3.0.0",
        "status": "withheld",
        "action": "NO_TRADE",
        "overall_score": None,
        "data_quality": "LOW_CONFIDENCE",
        "coverage": coverage,
        "reason": reason,
        "probability": None,
    }


def _calendar_context(calendar, *, as_of_date, as_of_timestamp, min_coverage):
    """Validate the independently supplied exchange-session calendar."""
    if not isinstance(calendar, dict):
        return None, "session_calendar_missing"
    if calendar.get("status") != "verified":
        return None, "session_calendar_not_verified"
    source_id = calendar.get("source_id")
    if not isinstance(source_id, str) or not source_id.strip():
        return None, "session_calendar_source_id_missing"
    coverage = _decimal(calendar.get("coverage"), "calendar_coverage")
    if coverage > 1:
        raise IDPATError("calendar_coverage_above_one")
    if coverage < min_coverage:
        return None, "session_calendar_coverage_below_threshold"
    available_at = _timestamp(calendar.get("available_at"), "calendar_available_at")
    cutoff = _timestamp(as_of_timestamp, "as_of_timestamp")
    if available_at > cutoff:
        return None, "session_calendar_not_available_at_cutoff"
    sessions = calendar.get("sessions")
    if not isinstance(sessions, list) or not sessions:
        return None, "verified_sessions_missing"
    parsed = []
    for item in sessions:
        if not isinstance(item, str):
            raise IDPATError("invalid_calendar_session")
        try:
            day = date.fromisoformat(item)
        except ValueError:
            raise IDPATError("invalid_calendar_session") from None
        if day.isoformat() != item:
            raise IDPATError("calendar_session_must_be_canonical_yyyy_mm_dd")
        parsed.append(day.isoformat())
    if parsed != sorted(set(parsed)):
        raise IDPATError("calendar_sessions_must_be_unique_and_ascending")
    if parsed[-1] > as_of_date:
        return None, "calendar_contains_future_session"
    return {
        "sessions": parsed,
        "source_id": source_id,
        "coverage": str(coverage),
        "available_at": available_at.isoformat(),
    }, None


def analyze_idpat_market_structure(
    snapshot: dict,
    *,
    as_of_date: str,
    as_of_timestamp: str,
    min_coverage: Decimal = Decimal("0.95"),
    session_calendar: dict | None = None,
    pivot_width: int = 2,
    equal_tolerance: float = 0.005,
) -> dict:
    """Return causal structure/liquidity observations from verified OHLCV.

    Daily events are generated by the existing market_structure module.
    Optional weekly/monthly context is generated only with a verified,
    point-in-time exchange-session calendar.
    """
    base = analyze_idpat_price_volume(
        snapshot,
        as_of_date=as_of_date,
        as_of_timestamp=as_of_timestamp,
        min_coverage=min_coverage,
    )
    symbol = snapshot.get("symbol") if isinstance(snapshot, dict) else None
    if base.get("status") != "partial_research_only":
        return _withheld(symbol, base.get("reason", "upstream_evidence_withheld"), base.get("coverage"))

    try:
        cutoff_day = date.fromisoformat(as_of_date)
    except (TypeError, ValueError):
        raise IDPATError("invalid_as_of_date") from None

    raw_bars = snapshot["price_volume"]["bars"]
    if len(raw_bars) < 21:
        return _withheld(symbol, "at_least_21_valid_bars_required", base.get("coverage"))

    # IDPAT-1 has already validated ascending dates, OHLC geometry, source,
    # coverage, availability timestamp and point-in-time cutoff.
    rows = [{
        "date": row["date"],
        "open": float(_decimal(row["open"], "bar_open")),
        "high": float(_decimal(row["high"], "bar_high")),
        "low": float(_decimal(row["low"], "bar_low")),
        "close": float(_decimal(row["close"], "bar_close")),
        "volume": float(_decimal(row["volume"], "bar_volume")),
    } for row in raw_bars]

    structure = detect_structure(
        rows, pivot_width=pivot_width, equal_tolerance=equal_tolerance
    )
    if structure.get("status") != "screened":
        return _withheld(symbol, "market_structure_insufficient_or_invalid", base.get("coverage"))

    events = structure.get("events", [])
    latest_day = rows[-1]["date"]
    latest_events = [event for event in events if event.get("date") == latest_day]
    event_types = {event.get("type") for event in latest_events}

    bullish_events = {"bos", "choch"}
    bullish_count = sum(
        1 for event in events
        if event.get("type") in bullish_events and event.get("direction") == "bullish"
    )
    bearish_count = sum(
        1 for event in events
        if event.get("type") in bullish_events and event.get("direction") == "bearish"
    )
    bullish_sweeps = sum(
        1 for event in events
        if event.get("type") == "liquidity_sweep" and event.get("side") == "low"
    )
    bearish_sweeps = sum(
        1 for event in events
        if event.get("type") == "liquidity_sweep" and event.get("side") == "high"
    )
    equal_highs = [event for event in events if event.get("type") == "equal_highs"]
    equal_lows = [event for event in events if event.get("type") == "equal_lows"]
    zones = [
        event for event in events
        if event.get("type") in {"fvg", "order_block", "zone_retest", "zone_invalidated"}
    ]

    # Wyckoff campaign events are consumed from the existing engine; they are
    # exposed as separate evidence and are not added again to any score.
    wyckoff = wyckoff_event_features([{
        "session_date": row["date"],
        "open": row["open"], "high": row["high"], "low": row["low"],
        "close": row["close"], "volume": row["volume"],
    } for row in rows])
    wyckoff_names = {"sos", "sow", "lps", "lpsy", "spring", "upthrust",
                     "jump_across_creek", "backup_to_creek"}
    campaign_events = [
        event for event in wyckoff.get("events", [])
        if event.get("event") in wyckoff_names
    ]

    calendar, calendar_reason = _calendar_context(
        session_calendar,
        as_of_date=cutoff_day.isoformat(),
        as_of_timestamp=as_of_timestamp,
        min_coverage=min_coverage,
    )
    if calendar is None:
        multi_timeframe = {
            "status": "withheld",
            "reason": calendar_reason,
            "alignment": "unavailable",
            "production_score": None,
        }
    else:
        multi_timeframe = evaluate_multitimeframe(
            rows,
            eligible=True,
            verified_sessions=calendar["sessions"],
            as_of=cutoff_day.isoformat(),
        )
        multi_timeframe["calendar_evidence"] = {
            "source_id": calendar["source_id"],
            "coverage": calendar["coverage"],
            "available_at": calendar["available_at"],
        }

    if any(event_type in event_types for event_type in ("bos", "choch")):
        current_structure = "break_of_structure_or_change_of_character"
    elif "liquidity_sweep" in event_types:
        current_structure = "liquidity_sweep_candidate"
    elif "zone_retest" in event_types:
        current_structure = "zone_retest_candidate"
    else:
        current_structure = "no_new_confirmed_structure_event"

    return {
        "symbol": symbol,
        "schema_version": "idpat-3.0.0",
        "status": "partial_research_only",
        "action": "NO_TRADE",
        "overall_score": None,
        "data_quality": base["data_quality"],
        "coverage": base["coverage"],
        "as_of_date": base["as_of_date"],
        "available_at": base["available_at"],
        "source_ids": base["source_ids"],
        "structure_bias": structure["bias"],
        "current_structure_context": current_structure,
        "components": {
            "liquidity_structure_evidence_partial": None,
            "multi_timeframe_confirmation_partial": None,
        },
        "liquidity_map": {
            "equal_highs_buy_side_candidates": equal_highs[-10:],
            "equal_lows_sell_side_candidates": equal_lows[-10:],
            "liquidity_sweeps": [
                event for event in events if event.get("type") == "liquidity_sweep"
            ][-20:],
            "inferred_zones": zones[-30:],
            "dealing_range": structure.get("dealing_range"),
        },
        "market_structure": {
            "latest_events": latest_events,
            "event_history": events[-40:],
            "pivot_width": structure["pivot_width"],
            "equal_tolerance": structure["equal_tolerance"],
        },
        "wyckoff_campaign_events": campaign_events[-30:],
        "multi_timeframe": multi_timeframe,
        "evidence_counts": {
            "bullish_bos_choch": bullish_count,
            "bearish_bos_choch": bearish_count,
            "sell_side_sweep_candidates": bullish_sweeps,
            "buy_side_sweep_candidates": bearish_sweeps,
            "equal_highs": len(equal_highs),
            "equal_lows": len(equal_lows),
            "zone_events": len(zones),
            "wyckoff_campaign_events": len(campaign_events),
        },
        "methodology_notes": [
            "BOS, CHoCH, pivots, equal highs/lows, sweeps and zones reuse the existing market_structure engine.",
            "A pivot is not available until its configured right-hand confirmation bars have closed.",
            "A sweep is a wick beyond a previously confirmed swing followed by a close back across that level.",
            "Equal highs/lows and zones are inferred chart levels, not verified order-book liquidity.",
            "SOS, SOW, LPS, LPSY, spring and upthrust observations are consumed from the existing Wyckoff engine without double-counting.",
            "Weekly/monthly context is evaluated only when a verified session calendar is supplied; incomplete periods are excluded by the existing multi-timeframe engine.",
        ],
        "limitations": [
            "Daily OHLCV cannot reveal hidden orders, beneficial ownership, institutional intent or operator activity.",
            "No broker footprint, live order book, intraday execution sequence or spread/depth evidence is inferred.",
            "Multi-timeframe alignment remains unavailable when verified session-calendar evidence is absent.",
            "No calibrated IDPAT score, probability, BUY/SELL, entry, stop, target or backtest result is emitted.",
            "Output remains NO_TRADE pending independent market, sector, liquidity, execution and reward/risk confirmation.",
        ],
    }
